// 8. Number Comparison Logic
/*Declare two numbers, scoreA = 75 and scoreB = 82. Write conditional statements (if / else
if / else) to compare them and print whether scoreA is greater than, less than, or equal to
scoreB using template literals
*/

// Answer


let scoreA = 75;
let scoreB = 82;

if (scoreA > scoreB) {
  console.log(`${scoreA} is greater than ${scoreB}`);
} else if (scoreA < scoreB) {
  console.log(`${scoreA} is less than ${scoreB}`);
} else {
  console.log(`${scoreA} is equal to ${scoreB}`);
}


